"""Regenerate RESULTS.md.

The document is generated so it cannot drift from the data. Headings and notes
come from `matrix.py`, numbers from the summary, and the break-even from
`pricing.py` - the same function the economics command reports.
"""
import json

from .. import analysis, matrix, paths, pricing

HELP = "regenerate RESULTS.md from results/summary.json"

_ANALYZE = "python3 -m bqbench run --matrix all && python3 -m bqbench analyze"

PREAMBLE = """# Results

Generated by `python3 -m bqbench results-doc` — do not edit by hand.

Medians over n = 6–18 interleaved repetitions, result cache off, on-demand
pricing, US multi-region. `ratio` is against the first variant; `p` is a
two-sided Mann-Whitney U on the slot-time distributions and is **indicative,
not definitive** — see [METHODOLOGY.md](METHODOLOGY.md#multiple-comparisons).

Raw per-job records with complete query plans are published as a release asset;
see the README.
"""

HEADER = ("| variant | n | slot-ms (median) | min..max | ratio | p | billed "
          "| records read | stages |\n|---|---:|---:|---|---:|---:|---:|---:|---:|")

UNSTABLE = ("> **Plans were not stable across repetitions for this comparison, so "
            "no plan-identity claim is made.** BigQuery's runtime adaptivity "
            "produced more than one stage sequence for the same SQL.")


def add_arguments(p):
    p.add_argument("--out", default=str(paths.ROOT / "RESULTS.md"),
                   help="default: RESULTS.md at the repository root")


def main(args):
    summary = json.load(open(paths.require(paths.SUMMARY, _ANALYZE)))
    rebuilds = json.load(open(paths.require(paths.REBUILD,
                                            "python3 -m bqbench rebuild")))
    sizes = json.load(open(paths.require(paths.FIXTURE_SIZES,
                                         "python3 -m bqbench fixtures")))

    chunks = [PREAMBLE]
    for entry in matrix.in_doc_order():
        if entry["key"] in summary:
            chunks.append(_comparison(entry, summary[entry["key"]]))
    chunks.append(_breakeven(summary, rebuilds, sizes))

    with open(args.out, "w") as fh:
        fh.write("\n".join(chunks))
    print(f"wrote {args.out}")
    return 0


def _comparison(entry, block):
    lines = [f"## {entry['title']}", ""]
    if entry["note"]:
        lines += [entry["note"], ""]
    lines += [f"> {block['claim']}", "", HEADER]
    for name, s in block["variants"].items():
        p = "—" if s["p_vs_base"] is None else f"{s['p_vs_base']:.3f}"
        stages = "n/a" if s["stages"] == 0 else s["stages"]
        lines.append(
            f"| `{name}` | {s['n']} | {s['slot_ms_median']:,.0f} | "
            f"{s['slot_ms_min']:,}..{s['slot_ms_max']:,} | {s['ratio_vs_base']} | "
            f"{p} | {analysis.format_bytes(s['bytes_billed'])} | "
            f"{s['records_read']:,} | {stages} |")
    lines += ["", " · ".join([
        "plans identical" if block["plans_identical"] else "plans differ",
        "records identical" if block["work_identical"] else "records differ",
        "billed bytes identical" if block["bytes_identical"] else "billed bytes differ",
    ])]
    if not block["plans_stable"]:
        lines += ["", UNSTABLE]
    return "\n".join(lines) + "\n"


def _breakeven(summary, rebuilds, sizes):
    b = pricing.denormalisation_breakeven(summary, rebuilds, sizes)
    return f"""## Denormalisation break-even

The measured cost of rebuilding the wide table against the measured per-query
saving — the arithmetic the advice never includes.

```
per-query saving   {b['saved_slot_ms']:>12,.0f} slot-ms   {b['saved_bytes']/2**20:>9.1f} MiB billed
one rebuild costs  {b['rebuild_slot_ms']:>12,.0f} slot-ms   {b['rebuild_bytes']/2**20:>9.1f} MiB billed   (median of {b['rebuilds']})

break-even, slot time  {b['breakeven_slot']:>6.1f} queries per rebuild
break-even, on-demand  {b['breakeven_bytes']:>6.1f} queries per rebuild

wide table         {b['wide_bytes']/2**30:>7.3f} GiB
3 normalised       {b['normalised_bytes']/2**30:>7.3f} GiB   -> denormalising costs {b['storage_overhead_pct']:+.1f}% storage
extra storage      ${b['storage_usd_month']:>7.3f}/month
nightly rebuild    ${b['nightly_usd_month']:>7.3f}/month   ({b['nightly_vs_storage']:.0f}x the storage)
```

Columnar compression absorbs nearly all the duplication, so the storage warning
attached to this advice is close to noise. The binding constraint is refresh
frequency: below roughly {b['breakeven_slot']:.0f}–{b['breakeven_bytes']:.0f} queries per rebuild cycle you spend more
refreshing the table than you save reading it.
"""
