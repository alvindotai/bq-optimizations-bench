PREAMBLE = """# Results

Generated by `python3 -m bqbench results-doc` — do not edit by hand.

Medians over n = 6–18 interleaved repetitions, result cache off, on-demand
pricing, US multi-region. `ratio` is against the first variant.

**Three meters, and they disagree.** `slot-ms` is aggregate slot consumption
across parallel workers — what capacity pricing bills. `elapsed-ms` is wall
clock — what a human waits. `billed` is bytes — what on-demand pricing charges,
and the only one of the three that is money here. A rewrite can move one and
not the others, so each ratio is reported against its own meter and none of
them is called "faster" or "cheaper" without saying which. `p` and `95% CI`
describe the slot-ms column only.

**`ratio` is computed within a pass, so it will not equal the two median
columns divided.** Fourteen of the comparisons were measured across two passes
on a shared slot pool, and a pass that ran busy slows both variants alike. That
shift cancels inside a pass and does not cancel in a pooled median, so the ratio
is taken per pass and the passes combined; `p` is a van Elteren stratified rank
test and the interval is a bootstrap resampled inside each pass. The median
columns stay pooled, because they describe what the jobs did. Where a
comparison ran in a single pass the two agree exactly. See
[METHODOLOGY.md](METHODOLOGY.md#blocking-by-pass).

**Read the CI, not the p-value.** `p` is a two-sided rank test and is
indicative only; `95% CI` is a percentile bootstrap on the median ratio, and it
is the column that says what a comparison actually establishes. A CI spanning
1.00 means no difference was detected — *and* bounds how large one could have
gone undetected. At these sample sizes that bound is often wide, so "no
difference" frequently means "nothing bigger than ±20%", not "identical".

Where a comparison shows identical plans, identical record counts and identical
billed bytes, that structural evidence is far stronger than the timing, and the
CI merely bounds any residual. See
[METHODOLOGY.md](METHODOLOGY.md#multiple-comparisons).

Raw per-job records with complete query plans are published as a release asset;
see the README.
"""

