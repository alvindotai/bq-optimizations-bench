def add_arguments(p):
    p.add_argument("--out", default=str(paths.ROOT / "RESULTS.md"),
                   help="default: RESULTS.md at the repository root")


def fmt_bytes(b):
    if isinstance(b, list):
        return " / ".join(fmt_bytes(x) for x in b)
    return f"{b/2**30:.2f} GiB" if b >= 2**30 else f"{b/2**20:,.0f} MiB"


def main(args):
    summary = json.load(open(paths.require(paths.SUMMARY, _RUN)))
    rebuilds = json.load(open(paths.require(paths.REBUILD,
                                            "python3 -m bqbench rebuild")))
    sizes = json.load(open(paths.require(paths.FIXTURE_SIZES,
                                         "python3 -m bqbench fixtures")))
    out = []
    w = out.append

    w("# Results\n")
    w("Generated by `python3 -m bqbench results-doc` — do not "
      "edit by hand.\n")
    w("Medians over n = 6–18 interleaved repetitions, result cache off, "
      "on-demand pricing, US multi-region. `ratio` is against the first variant; "
      "`p` is a two-sided Mann-Whitney U on the slot-time distributions and is "
      "**indicative, not definitive** — see "
      "[METHODOLOGY.md](METHODOLOGY.md#multiple-comparisons).\n")
    w("Raw per-job records with complete query plans: "
      "`results/all_results.jsonl`.\n")

    for title, key, note in SECTIONS:
        block = summary[key]
        w(f"## {title}\n")
        if note:
            w(note + "\n")
        w(f"> {block['claim']}\n")
        w("| variant | n | slot-ms (median) | min..max | ratio | p | billed | records read | stages |")
        w("|---|---:|---:|---|---:|---:|---:|---:|---:|")
        for name, s in block["variants"].items():
            p = "—" if s["p_vs_base"] is None else f"{s['p_vs_base']:.3f}"
            stages = "n/a" if s["stages"] == 0 else s["stages"]
            w(f"| `{name}` | {s['n']} | {s['slot_ms_median']:,.0f} | "
              f"{s['slot_ms_min']:,}..{s['slot_ms_max']:,} | {s['ratio_vs_base']} | "
              f"{p} | {fmt_bytes(s['bytes_billed'])} | {s['records_read']:,} | {stages} |")
        flags = [
            "plans identical" if block["plans_identical"] else "plans differ",
            "records identical" if block["work_identical"] else "records differ",
            "billed bytes identical" if block["bytes_identical"] else "billed bytes differ",
        ]
        w("")
        w(" · ".join(flags))
        if not block["plans_stable"]:
            w("\n> **Plans were not stable across repetitions for this comparison, "
              "so no plan-identity claim is made.** BigQuery's runtime adaptivity "
              "produced more than one stage sequence for the same SQL.")
        w("")

    # ---- economics, computed from the same data economics.py uses ----
    m6 = summary["m6_denormalisation"]["variants"]
    star, flat = m6["star_join_3_tables"], m6["denormalised_1_table"]
    rb_slot = statistics.median(r["slot_ms"] for r in rebuilds)
    rb_bytes = statistics.median(r["bytes_billed"] for r in rebuilds)
    d_slot = star["slot_ms_median"] - flat["slot_ms_median"]
    d_bytes = star["bytes_billed"] - flat["bytes_billed"]
    wide = sizes["denorm_wide"]["bytes"]
    parts = sum(sizes[t]["bytes"] for t in NORMALISED)
    storage_mo = wide / 2**30 * STORAGE_USD_PER_GIB_MONTH
    rebuild_mo = rb_bytes / 2**40 * ON_DEMAND_USD_PER_TIB * 30

    w("## Denormalisation break-even\n")
    w("The measured cost of rebuilding the wide table against the measured "
      "per-query saving — the arithmetic the advice never includes.\n")
    w("```")
    w(f"per-query saving   {d_slot:>12,.0f} slot-ms   {d_bytes/2**20:>9.1f} MiB billed")
    w(f"one rebuild costs  {rb_slot:>12,.0f} slot-ms   {rb_bytes/2**20:>9.1f} MiB billed"
      f"   (median of {len(rebuilds)})")
    w("")
    w(f"break-even, slot time  {rb_slot/d_slot:>6.1f} queries per rebuild")
    w(f"break-even, on-demand  {rb_bytes/d_bytes:>6.1f} queries per rebuild")
    w("")
    w(f"wide table         {wide/2**30:>7.3f} GiB")
    w(f"3 normalised       {parts/2**30:>7.3f} GiB   "
      f"-> denormalising costs {100*(wide-parts)/parts:+.1f}% storage")
    w(f"extra storage      ${storage_mo:>7.3f}/month")
    w(f"nightly rebuild    ${rebuild_mo:>7.3f}/month   "
      f"({rebuild_mo/storage_mo:.0f}x the storage)")
    w("```\n")
    w("Columnar compression absorbs nearly all the duplication, so the storage "
      "warning attached to this advice is close to noise. The binding constraint "
      f"is refresh frequency: below roughly {rb_slot/d_slot:.0f}–{rb_bytes/d_bytes:.0f} "
      "queries per rebuild cycle you spend more refreshing the table than you "
      "save reading it.\n")

    with open(args.out, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"wrote {args.out} ({len(out)} blocks)")
    return 0