"""Where things live on disk.

`results/` is generated by a run, not committed; set BENCH_RESULTS to move it.
"""
import json
import os
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SQL = ROOT / "sql"
RESULTS = pathlib.Path(os.environ.get("BENCH_RESULTS") or ROOT / "results")

ALL_RESULTS = RESULTS / "all_results.jsonl"
SUMMARY = RESULTS / "summary.json"
REBUILD = RESULTS / "rebuild.json"
FIXTURE_SIZES = RESULTS / "fixture_sizes.json"


def ensure_results_dir():
    RESULTS.mkdir(parents=True, exist_ok=True)
    return RESULTS


def require(path, produced_by):
    """Fail with an instruction rather than a traceback when a run is missing."""
    if not path.exists():
        raise SystemExit(f"missing {path}\n"
                         f"  results/ is not committed. Generate it with:\n"
                         f"      {produced_by}")
    return path


def read_json(path, produced_by):
    """Load a JSON artefact a run should have produced."""
    with open(require(path, produced_by)) as fh:
        return json.load(fh)
